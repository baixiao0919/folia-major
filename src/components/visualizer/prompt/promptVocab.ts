/** 所有可用的中文词（按 id 升序，同一个 id 永远同一个词）。 */
export const PROMPT_VOCAB: readonly PromptVocabEntry[] = PACK.split(' ').map((chunk) => {
    const cut = chunk.search(/[^0-9]/);
    return { id: Number(chunk.slice(0, cut)), text: chunk.slice(cut) };
});

const mix = (a: number, b: number): number => {
    let hash = (Math.imul((a | 0) ^ 0x9e3779b9, 16777619) ^ Math.imul((b | 0) + 0x85ebca6b, 2246822519)) >>> 0;
    hash ^= hash >>> 13;
    hash = Math.imul(hash, 0x5bd1e995) >>> 0;
    hash ^= hash >>> 15;
    return hash >>> 0;
};

/**
 * 按种子取第 `slot` 个词：同一个 (种子, 槽位) 永远同一个词。
 * 步长取 97–296 且词条数是素数，所以同屏几个槽位（0–4）算出来的下标一定不撞。
 */
export const promptVocabPick = (seed: number, slot: number): PromptVocabEntry => {
    const size = PROMPT_VOCAB.length;
    const base = mix(seed, 17) % size;
    const stride = 97 + (mix(seed, 977) % 200);
    return PROMPT_VOCAB[(base + stride * slot) % size];
};

/** 面板 / 信息条上印的五位数字：真实词表 id，不足五位前补 0。 */
export const promptVocabLabel = (seed: number, slot: number): string => (
    String(promptVocabPick(seed, slot).id).padStart(5, '0')
);

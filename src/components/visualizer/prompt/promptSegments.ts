export interface PromptSegment {
    text: string;
    start: number;
    end: number;
}

/**
 * 最长的词有多长（词典里 2–4 字，取一遍最大值，逐字扫描时不用每步都试 4 次）。
 */
const MAX_WORD = 4;

const ASCII = /[A-Za-z0-9]/;
const CJK = /[\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]/;

const isAscii = (ch: string) => ASCII.test(ch);
const isCjk = (ch: string) => CJK.test(ch);
const isSpace = (ch: string) => /\s/.test(ch);

/**
 * 词表切分：西文连成词、空白成段、中日韩按词典最长匹配（匹配不上就单字）。
 * 返回的区间可以直接拿去 `slice`，也能拿去量宽画逐词下划线。
 */
export const segmentWithVocab = (text: string): PromptSegment[] => {
    const out: PromptSegment[] = [];
    if (!text) return out;
    let index = 0;
    while (index < text.length) {
        const head = text[index];
        if (isSpace(head)) {
            let end = index;
            while (end < text.length && isSpace(text[end])) end += 1;
            out.push({ text: text.slice(index, end), start: index, end });
            index = end;
            continue;
        }
        if (isAscii(head)) {
            let end = index;
            while (end < text.length && (isAscii(text[end]) || text[end] === "'" || text[end] === "-" || text[end] === "\u2019")) end += 1;
            out.push({ text: text.slice(index, end), start: index, end });
            index = end;
            continue;
        }
        if (isCjk(head)) {
            let size = Math.min(MAX_WORD, text.length - index);
            for (; size > 1; size -= 1) {
                if (DICTIONARY.has(text.slice(index, index + size))) break;
            }
            out.push({ text: text.slice(index, index + size), start: index, end: index + size });
            index += size;
            continue;
        }
        out.push({ text: head, start: index, end: index + 1 });
        index += 1;
    }
    return out;
};
